"""Reusable mapped-column mixins shared across ORM models."""

from datetime import datetime

from sqlalchemy import DateTime, func
from sqlalchemy.orm import Mapped, mapped_column


class TimestampMixin:
    """Adds UTC-aware ``created_at``/``updated_at`` columns.

    Timestamps are generated by the database (``server_default=func.now()``)
    rather than in application code, so they are consistent regardless of
    which process/timezone the app server is running in, and correct even
    for rows inserted outside the ORM (e.g. a raw migration data fix).
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
